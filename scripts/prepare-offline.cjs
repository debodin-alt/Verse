// Deterministically pin the complete static release; no dependencies or app data.
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const root = path.resolve(__dirname, '..');
const assets = ['index.html','app.js','offline.js','style.css','manifest.webmanifest','icon.svg','icon-192.png','icon-512.png'];
const sha = value => createHash('sha256').update(value).digest('hex');
function buildWorker(files, template = fs.readFileSync(path.join(__dirname,'service-worker.js'),'utf8')) {
  const manifest = assets.map(name => ({name,sha256:sha(files[name])}));
  const version = sha(template + JSON.stringify(manifest)).slice(0,24);
  return '// Generated by npm run prepare:offline. Edit scripts/service-worker.js.\n' + template
    .replace('__SHELL_VERSION__',version).replace('/*__SHELL_ASSETS__*/[]',JSON.stringify(manifest,null,2));
}
if (require.main === module) {
  const files = Object.fromEntries(assets.map(name=>[name,fs.readFileSync(path.join(root,'dist',name))]));
  const output = buildWorker(files), target = path.join(root,'dist/sw.js');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) {
      console.error('Offline shell is stale. Run npm run prepare:offline after editing static app files.');
      process.exitCode = 1;
    } else console.log('Offline shell matches all static app files.');
  } else {fs.writeFileSync(target,output);console.log('Prepared versioned offline shell.');}
}
module.exports = {assets,buildWorker};
