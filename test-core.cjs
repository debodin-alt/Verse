const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({crypto:require('node:crypto').webcrypto,Blob,atob,structuredClone,console});
vm.runInContext(fs.readFileSync('dist/app.js','utf8').replace(/init\(\);\s*$/, ''),context);
const run = code => vm.runInContext(code,context);
assert.deepEqual(Array.from(run("chordNotes('C')")), [48,52,55]);
assert.deepEqual(Array.from(run("chordNotes('Am7')")), [57,60,64,67]);
assert.deepEqual(Array.from(run("chordNotes('G7')")), [55,59,62,65]);
assert.equal(run("chordNotes('<script>').length"),0);
assert.equal(run("escapeHTML('<script>')"),'&lt;script&gt;');
run(`var original=makeIdea('Backup round trip'); original.lyrics='Words worth keeping'; original.takes=[{name:'Test take',audio:'data:audio/webm;base64,AQIDBA==',withLoop:true}]; var restored=validateImport(JSON.parse(JSON.stringify(original)));`);
assert.equal(run('restored.lyrics'),'Words worth keeping');
assert.equal(run('restored.takes[0].blob.size'),4);
assert.equal(run('restored.takes[0].blob.type'),'audio/webm');
assert.equal(run('restored.takes[0].withLoop'),true);
assert.notEqual(run('restored.id'),run('original.id'));
assert.equal(run("validateImport({...original,bpm:999}).bpm"),200);
assert.throws(()=>run("validateImport({...original,takes:[{audio:'https://example.com/track'}]})"));
assert.throws(()=>run("validateImport({title:'Incomplete'})"));
run('original.created=123456; original.updated=234567; var dated=validateImport(original);');
assert.equal(run('dated.created'),123456,'Restore must retain original creation time');
assert.equal(run('dated.updated'),234567,'Restore must retain original modification time');
assert.equal(run('validateImport({...original,created:0,updated:0}).created'),0,'Epoch timestamps are valid');
assert.equal(run('validateImport({...original,created:-1}).created >= 0'),true);
assert.equal(run('Number.isFinite(validateImport({...original,created:Infinity}).created)'),true);
assert.equal(run("validateImport({...original,created:'123456'}).created"),123456,'Legacy numeric timestamps remain compatible');
console.log('Passed 19 checks: chords, escaping, audio restore, new identities, tempo bounds, invalid import and timestamp preservation.');
